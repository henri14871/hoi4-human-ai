"""Generate the in-game panel (the Workshop mod) from one table.

Writes, relative to workshop/ (the mod folder uploaded to Steam Workshop):
  interface/hai_panel.gui                       layout
  common/scripted_guis/hai_panel.txt            buttons -> flags + "HAI_CMD <key> <0|1>" log lines
  common/on_actions/hai_on_actions.txt          send the campaign's saved state to the dll on load
  localisation/english/hai_l_english.yml        text

The dll watches game.log for HAI_CMD lines (native/src/hai.cpp, PollGameLog) and writes
them to human_ai.ini. Settings live in global flags, so each campaign keeps its own:
loading a save or opening the panel re-sends them.

Everything is inlined: HoI4 loads scripted GUIs before scripted effects, so the
GUI can't call scripted effects.

usage: py tools/gen_panel.py
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "workshop")

# (config key, label, tooltip) grouped by section. Keys must match kCategoryKeys in hai.cpp.
GROUPS = [
    ("Government", [
        ("foreign", "Diplomacy", "Guarantees, factions, wars, lend-lease"),
        ("political", "Politics", "National focus, laws, advisors, scientists"),
        ("interior", "Economy", "Trade, garrisons, equipment and ship designs"),
    ]),
    ("Armed forces", [
        ("land", "Land forces", "Fronts, armies, army groups, invasions"),
        ("air", "Air force", "Air bases and air missions"),
        ("navy", "Navy", "Naval objectives and fleets"),
        ("volunteers", "Volunteers", "Volunteer forces sent abroad"),
    ]),
    ("Intelligence", [
        ("cryptology", "Cryptology", "Code breaking"),
    ]),
]
KEYS = [k for _, rows in GROUPS for k, _, _ in rows]

WIDTH = 420
ROW_H = 36
HEADER_H = 28
BUTTON_X = WIDTH - 94 - 22  # GFX_button_94x31


def flag(key):
    return f"hai_{key}_ai"


def write(rel, text, bom=False):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8-sig" if bom else "utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", rel)


def gui():
    rows, y = [], 56
    for gi, (title, items) in enumerate(GROUPS):
        rows.append(f"""
		instantTextBoxType = {{
			name = "hai_group_{gi}"
			position = {{ x = 20 y = {y} }}
			font = "hoi_20bs"
			text = "HAI_GROUP_{gi}"
			maxWidth = {WIDTH - 40}
			maxHeight = 24
			fixedsize = yes
		}}""")
        y += HEADER_H
        for key, _, _ in items:
            rows.append(f"""
		instantTextBoxType = {{
			name = "hai_{key}_label"
			position = {{ x = 32 y = {y + 6} }}
			font = "hoi_18mbs"
			text = "HAI_{key.upper()}"
			maxWidth = {BUTTON_X - 40}
			maxHeight = 22
			fixedsize = yes
			pdx_tooltip = "HAI_{key.upper()}_DESC"
		}}
		buttonType = {{
			name = "hai_{key}_to_ai"
			position = {{ x = {BUTTON_X} y = {y} }}
			quadTextureSprite = "GFX_button_94x31"
			buttonText = "HAI_YOU"
			buttonFont = "hoi_16mbs"
			clicksound = click_default
			pdx_tooltip = "HAI_TO_AI_TT"
		}}
		buttonType = {{
			name = "hai_{key}_to_me"
			position = {{ x = {BUTTON_X} y = {y} }}
			quadTextureSprite = "GFX_button_94x31"
			buttonText = "HAI_AI"
			buttonFont = "hoi_16mbs"
			clicksound = click_default
			pdx_tooltip = "HAI_TO_ME_TT"
		}}""")
            y += ROW_H
        y += 8
    buttons_y = y + 6
    height = buttons_y + 34 + 44
    return f"""# Generated by tools/gen_panel.py - edit that instead.
guiTypes = {{

	# Small launcher button, bottom left.
	containerWindowType = {{
		name = "hai_toggle_window"
		orientation = lower_left
		position = {{ x = 10 y = -80 }}
		size = {{ width = 123 height = 34 }}

		buttonType = {{
			name = "hai_toggle"
			position = {{ x = 0 y = 0 }}
			quadTextureSprite = "GFX_button_123x34"
			buttonText = "HAI_TOGGLE"
			buttonFont = "hoi_16mbs"
			clicksound = click_default
			pdx_tooltip = "HAI_TOGGLE_TT"
		}}
	}}

	containerWindowType = {{
		name = "hai_panel_window"
		orientation = lower_left
		position = {{ x = 10 y = {-(height + 90)} }}
		size = {{ width = {WIDTH} height = {height} }}
		moveable = yes

		background = {{
			name = "Background"
			quadTextureSprite = "GFX_tiled_window_2b_border"
		}}

		instantTextBoxType = {{
			name = "hai_title"
			position = {{ x = 20 y = 14 }}
			font = "hoi_24header"
			text = "HAI_TITLE"
			maxWidth = {WIDTH - 80}
			maxHeight = 30
			fixedsize = yes
		}}

		buttonType = {{
			name = "hai_close"
			position = {{ x = -44 y = 10 }}
			orientation = upper_right
			quadTextureSprite = "GFX_closebutton"
			clicksound = click_close
			pdx_tooltip = "CLOSE"
		}}
{''.join(rows)}

		buttonType = {{
			name = "hai_all_ai"
			position = {{ x = 40 y = {buttons_y} }}
			quadTextureSprite = "GFX_button_148x34"
			buttonText = "HAI_ALL_AI"
			buttonFont = "hoi_16mbs"
			clicksound = click_default
		}}
		buttonType = {{
			name = "hai_all_me"
			position = {{ x = {WIDTH - 40 - 148} y = {buttons_y} }}
			quadTextureSprite = "GFX_button_148x34"
			buttonText = "HAI_ALL_ME"
			buttonFont = "hoi_16mbs"
			clicksound = click_default
		}}

		instantTextBoxType = {{
			name = "hai_footer"
			position = {{ x = 20 y = {buttons_y + 44} }}
			font = "hoi_16mbs"
			text = "HAI_FOOTER"
			maxWidth = {WIDTH - 40}
			maxHeight = 20
			fixedsize = yes
		}}
	}}
}}
"""


def sync_block(indent):
    """Log every area's current state, from the campaign's flags."""
    t = "\t" * indent
    return "".join(f"""
{t}if = {{
{t}	limit = {{ has_global_flag = {flag(k)} }}
{t}	log = "HAI_CMD {k} 1"
{t}}}
{t}else = {{ log = "HAI_CMD {k} 0" }}""" for k in KEYS)


def set_all_block(ai, indent):
    t = "\t" * indent
    op = "set_global_flag" if ai else "clr_global_flag"
    return "".join(f'\n{t}{op} = {flag(k)}\n{t}log = "HAI_CMD {k} {int(ai)}"' for k in KEYS)


def scripted_gui():
    effects, triggers = [], []
    for k in KEYS:
        effects.append(f"""
			hai_{k}_to_ai_click = {{ set_global_flag = {flag(k)} log = "HAI_CMD {k} 1" }}
			hai_{k}_to_me_click = {{ clr_global_flag = {flag(k)} log = "HAI_CMD {k} 0" }}""")
        triggers.append(f"""
			hai_{k}_to_ai_visible = {{ NOT = {{ has_global_flag = {flag(k)} }} }}
			hai_{k}_to_me_visible = {{ has_global_flag = {flag(k)} }}""")
    return f"""# Generated by tools/gen_panel.py - edit that instead.
scripted_gui = {{

	hai_toggle_gui = {{
		context_type = player_context
		window_name = "hai_toggle_window"
		visible = {{ always = yes }}
		ai_enabled = {{ always = no }}
		effects = {{
			hai_toggle_click = {{
				if = {{
					limit = {{ has_global_flag = hai_panel_open }}
					clr_global_flag = hai_panel_open
				}}
				else = {{
					set_global_flag = hai_panel_open
					# Opening the panel makes the dll match what it shows.{sync_block(5)}
				}}
			}}
		}}
	}}

	hai_panel_gui = {{
		context_type = player_context
		window_name = "hai_panel_window"
		visible = {{ has_global_flag = hai_panel_open }}
		# The AI must never press these: with human_ai on, the game treats the player as AI.
		ai_enabled = {{ always = no }}
		effects = {{
			hai_close_click = {{ clr_global_flag = hai_panel_open }}
			hai_all_ai_click = {{{set_all_block(True, 4)}
			}}
			hai_all_me_click = {{{set_all_block(False, 4)}
			}}{''.join(effects)}
		}}
		triggers = {{{''.join(triggers)}
		}}
	}}
}}
"""


def on_actions():
    return f"""# Generated by tools/gen_panel.py - edit that instead.
# Tell the dll this campaign's saved settings when it starts or loads.
on_actions = {{
	on_startup = {{
		effect = {{{sync_block(3)}
		}}
	}}
}}
"""


def descriptor():
    # The launcher-facing descriptor; tools/package.py adds the path line for local installs.
    return """version="0.1.0"
tags={
	"Gameplay"
	"Utilities"
}
name="Human AI"
supported_version="1.19.*"
"""


def localisation():
    lines = [
        "l_english:",
        ' HAI_TITLE:0 "Human AI"',
        ' HAI_TOGGLE:0 "Human AI"',
        ' HAI_TOGGLE_TT:0 "Choose which parts of your country the AI runs for you."',
        ' HAI_YOU:0 "You"',
        ' HAI_AI:0 "§YAI§!"',
        ' HAI_TO_AI_TT:0 "You control this. Click to hand it to the AI."',
        ' HAI_TO_ME_TT:0 "The AI controls this. Click to take it back."',
        ' HAI_ALL_AI:0 "All to AI"',
        ' HAI_ALL_ME:0 "All to me"',
        ' HAI_FOOTER:0 "§gSaved with this campaign. Needs version.dll - see the mod page.§!"',
    ]
    for gi, (title, items) in enumerate(GROUPS):
        lines.append(f' HAI_GROUP_{gi}:0 "{title}"')
        for k, label, desc in items:
            lines.append(f' HAI_{k.upper()}:0 "{label}"')
            lines.append(f' HAI_{k.upper()}_DESC:0 "{desc}"')
    return "\n".join(lines) + "\n"


write("descriptor.mod", descriptor())
write("interface/hai_panel.gui", gui())
write("common/scripted_guis/hai_panel.txt", scripted_gui())
write("common/on_actions/hai_on_actions.txt", on_actions())
write("localisation/english/hai_l_english.yml", localisation(), bom=True)
